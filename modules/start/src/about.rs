fn reg_str(key: &str, value: &str) -> Option<String> {
    let mut buf = [0u16; 256];
    let mut size = size_of_val(&buf) as u32;
    // SAFETY: `buf` is writable for `size` bytes; the HSTRINGs outlive the call.
    unsafe {
        RegGetValueW(HKEY_LOCAL_MACHINE, &HSTRING::from(key), &HSTRING::from(value), RRF_RT_REG_SZ, None, Some(buf.as_mut_ptr().cast()), Some(&mut size))
    }
    .ok()
    .ok()?;
    let len = buf.iter().position(|&c| c == 0).unwrap_or(buf.len());
    Some(String::from_utf16_lossy(&buf[..len]).trim().to_string())
}

fn reg_dword(key: &str, value: &str) -> Option<u32> {
    let mut v = 0u32;
    let mut size = 4u32;
    // SAFETY: `v` is writable for `size` (4) bytes; the HSTRINGs outlive the call.
    unsafe {
        RegGetValueW(HKEY_LOCAL_MACHINE, &HSTRING::from(key), &HSTRING::from(value), RRF_RT_REG_DWORD, None, Some((&mut v as *mut u32).cast()), Some(&mut size))
    }
    .ok()
    .ok()?;
    Some(v)
}

/// Removes marketing suffixes like "(R)", "(TM)", " CPU", and clock speeds.
fn tidy(s: &str) -> String {
    let s = s.replace("(R)", "").replace("(TM)", "").replace(" CPU", "");
    let s = s.split(" @ ").next().unwrap_or("");
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Formats a float to 1 decimal place, using a comma for Russian locale.
fn num(v: f64, ru: bool) -> String {
    let s = format!("{v:.1}");
    let s = s.strip_suffix(".0").map(String::from).unwrap_or(s);
    if ru { s.replace('.', ",") } else { s }
}

fn windows_version() -> String {
    let key = r"SOFTWARE\Microsoft\Windows NT\CurrentVersion";
    let build: u32 = reg_str(key, "CurrentBuildNumber").and_then(|b| b.parse().ok()).unwrap_or(0);
    // Registry still reports "Windows 10" for Windows 11; check build number >= 22000.
    let mut name = reg_str(key, "ProductName").unwrap_or_else(|| "Windows".into());
    if build >= 22000 {
        name = name.replace("Windows 10", "Windows 11");
    }
    let mut parts = vec![name];
    parts.extend(reg_str(key, "DisplayVersion"));
    let ubr = reg_dword(key, "UBR").map_or(String::new(), |u| format!(".{u}"));
    parts.push(format!("{build}{ubr}"));
    parts.join(" · ")
}

fn computer_name() -> String {
    let mut buf = [0u16; 256];
    let mut len = buf.len() as u32;
    // SAFETY: `buf` is writable for `len` characters.
    unsafe { GetComputerNameExW(ComputerNamePhysicalDnsHostname, Some(PWSTR(buf.as_mut_ptr())), &mut len) }
        .map_or_else(|_| "PC".into(), |()| String::from_utf16_lossy(&buf[..len as usize]))
}

fn gpus() -> String {
    let mut names: Vec<String> = Vec::new();
    // SAFETY: DXGI calls on live COM objects; `desc` is returned by value.
    unsafe {
        let Ok(factory) = CreateDXGIFactory1::<IDXGIFactory1>() else { return String::new() };
        let mut i = 0;
        while let Ok(adapter) = factory.EnumAdapters1(i) {
            i += 1;
            let Ok(desc) = adapter.GetDesc1() else { continue };
            if desc.Flags & DXGI_ADAPTER_FLAG_SOFTWARE.0 as u32 != 0 {
                continue;
            }
            let len = desc.Description.iter().position(|&c| c == 0).unwrap_or(desc.Description.len());
            let name = tidy(&String::from_utf16_lossy(&desc.Description[..len]));
            if !names.contains(&name) {
                names.push(name);
            }
        }
    }
    names.join(" + ")
}

fn uptime(t: &Strings) -> String {
    // SAFETY: `GetTickCount64` has no preconditions.
    let m = unsafe { GetTickCount64() } / 60_000;
    let (d, h, m) = (m / 1440, m / 60 % 24, m % 60);
    match (d, h) {
        (0, 0) => format!("{m} {}", t.min),
        (0, _) => format!("{h} {} {m} {}", t.h, t.min),
        _ => format!("{d} {} {h} {}", t.d, t.h),
    }
}

pub fn screen() -> Screen {
    let lang = proto::language();
    let ru = lang == "ru";
    let t = match lang {
        "ru" => &RU,
        "zh" => &ZH,
        "ja" => &JA,
        _ => &EN,
    };
    let pair = |label: &str, value: String| Row::Pair { label: label.into(), value };
    let mut rows: Vec<Row> = art().into_iter().collect();
    rows.push(Row::Header { title: computer_name(), subtitle: windows_version() });

    if let Some(cpu) = reg_str(r"HARDWARE\DESCRIPTION\System\CentralProcessor\0", "ProcessorNameString") {
        rows.push(pair(t.cpu, tidy(&cpu)));
    }
    let mut mem = MEMORYSTATUSEX { dwLength: size_of::<MEMORYSTATUSEX>() as u32, ..Default::default() };
    // SAFETY: `mem` is initialized with its `dwLength` and outlives the call.
    if unsafe { GlobalMemoryStatusEx(&mut mem) }.is_ok() {
        let total = mem.ullTotalPhys as f64 / GB;
        let used = (mem.ullTotalPhys - mem.ullAvailPhys) as f64 / GB;
        rows.push(pair(t.memory, format!("{} {} · {} {}", total.round(), t.gb, t.used, num(used, ru))));
    }
    let gpu = gpus();
    if !gpu.is_empty() {
        rows.push(pair(t.gpu, gpu));
    }
    let drive = std::env::var("SystemDrive").unwrap_or_else(|_| "C:".into());
    let (mut free, mut total) = (0u64, 0u64);
    // SAFETY: the path HSTRING and the out pointers outlive the call.
    if unsafe { GetDiskFreeSpaceExW(&HSTRING::from(format!("{drive}\\")), None, Some(&mut total), Some(&mut free)) }.is_ok() {
        rows.push(pair(&format!("{} {drive}", t.disk), format!("{} {} · {} {}", (total as f64 / GB).round(), t.gb, t.free, (free as f64 / GB).round())));
    }
    rows.push(pair(t.uptime, uptime(t)));
    Screen { title: Some(t.title.into()), rows }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tidy_names() {
        assert_eq!(tidy("11th Gen Intel(R) Core(TM) i7-1165G7 @ 2.80GHz"), "11th Gen Intel Core i7-1165G7");
        assert_eq!(tidy("Intel(R) UHD Graphics"), "Intel UHD Graphics");
    }

    #[test]
    fn art_parses() {
        let Some(Row::Art { lines, colors }) = art() else { panic!("the art did not parse") };
        assert!(!lines.is_empty());
        assert_eq!(lines.len(), colors.len());
    }

    #[test]
    fn numbers() {
        assert_eq!(num(9.24, true), "9,2");
        assert_eq!(num(16.0, false), "16");
    }
}
